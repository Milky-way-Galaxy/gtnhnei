import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { resolve, posix } from "node:path";
const root = resolve(import.meta.dirname, "..");
// Follow the application's module graph. Include local assets requested by the
// Python worker/easter egg explicitly; do not cache dev tools or recipe atlases.
const queue = ["index.html", "favicon.svg", "data/manifest.json", "gtnhflow-pyodide-worker.js", "vendor/gtnh-flow-browser.zip", "assets/easter/luna.png"], seen = new Set();
while (queue.length) {
  const file = queue.shift(); if (seen.has(file)) continue; seen.add(file);
  const content = await readFile(resolve(root, file), "utf8");
  const dependencies = file.endsWith(".html") ? [...content.matchAll(/(?:src|href)="([^"#]+)"/g)].map(match => match[1]) :
    file.endsWith(".js") ? [...content.matchAll(/(?:from\s*|import\s*\(?\s*)["'](\.[^"']+)["']/g)].map(match => match[1]) : [];
  for (const dependency of dependencies) {
    if (/^[a-z]+:|^\//i.test(dependency)) continue;
    const path = posix.normalize(posix.join(posix.dirname(file), dependency.split("?")[0]));
    if (path.startsWith("../")) throw new Error("Offline asset escapes the repository.");
    queue.push(path);
  }
}
const files = [...seen];
files.sort();
const hash = createHash("sha256");
for (const file of [...files, "service-worker.js", "tools/stage-site.js"]) { hash.update(file); hash.update(await readFile(resolve(root, file))); }
const manifest = JSON.parse(await readFile(resolve(root, "data/manifest.json"), "utf8"));
const atlases = manifest.datasets.filter(dataset => dataset.available).map(({ atlasUrl, atlasSha256 }) => ({ atlasUrl, atlasSha256 }));
const output = `// Generated by npm run offline:manifest. Do not edit manually.\nexport const BUILD_ID = ${JSON.stringify(hash.digest("hex").slice(0, 20))};\nexport const SHELL_FILES = ${JSON.stringify(files, null, 2)};\nexport const ATLASES = ${JSON.stringify(atlases, null, 2)};\n`;
const path = resolve(root, "offline-manifest.js");
if (process.argv.includes("--write")) { await writeFile(path, output); console.log(`Generated offline shell: ${files.length} assets.`); }
else {
  if (await readFile(path, "utf8").catch(() => "") !== output) throw new Error("Offline shell is stale. Run npm run offline:manifest and commit offline-manifest.js.");
  console.log(`Offline shell verified: ${files.length} assets, both versions' atlas hashes pinned.`);
}
